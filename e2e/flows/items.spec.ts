// Registering items through the screens, for different kinds of item.
import { test, expect } from '@playwright/test'
import { apiAs, makeImei, signIn, uniq, watch } from '../support'

test.beforeEach(async ({ page }) => { await signIn(page, 'user') })

test('register a phone with a brand that is not in the list', async ({ page }) => {
  const w = watch(page)
  const imei = makeImei()
  await page.goto('/register-device')
  await page.getByRole('radio', { name: /phone/i }).click()
  await page.locator('#reg-brand').selectOption('Others')
  // Regression: this box used to vanish as soon as you typed in it
  const brand = page.getByLabel('Brand name')
  await brand.pressSequentially('Itel')
  await expect(brand).toBeVisible()
  await expect(brand).toHaveValue('Itel')
  const model = page.locator('#reg-model')
  if (await model.evaluate((el) => el.tagName === 'SELECT')) await model.selectOption({ index: 1 })
  else await model.fill('A70')
  await page.locator('#reg-imei').fill(imei)
  await page.getByRole('button', { name: /^next/i }).click()
  await page.getByRole('button', { name: /skip for now/i }).click()
  await page.getByRole('button', { name: /register item/i }).click()
  await expect(page).toHaveURL(/\/device\/[^/?]+\?new=1/, { timeout: 20_000 })
  await expect(page.getByText('Itel').first()).toBeVisible()

  await page.goto('/my-devices')
  await expect(page.getByText('Itel').first()).toBeVisible()
  w.expectClean()
})

test('register a laptop and a car', async ({ page }) => {
  await page.goto('/register-device')
  await page.getByRole('radio', { name: /laptop/i }).click()
  const brand = page.locator('#reg-brand')
  if (await brand.evaluate((el) => el.tagName === 'SELECT')) await brand.selectOption({ index: 1 }); else await brand.fill('Lenovo')
  const model = page.locator('#reg-model')
  if (await model.evaluate((el) => el.tagName === 'SELECT')) await model.selectOption({ index: 1 }); else await model.fill('ThinkPad X1')
  await page.locator('#reg-serial').fill(`SN${uniq()}`.toUpperCase().slice(0, 16))
  await page.getByRole('button', { name: /^next/i }).click()
  await page.getByRole('button', { name: /skip for now/i }).click()
  await page.getByRole('button', { name: /register item/i }).click()
  await expect(page).toHaveURL(/\/device\//, { timeout: 20_000 })

  await page.goto('/register-device')
  await page.getByRole('radio', { name: /^car$/i }).click()
  const vb = page.locator('#reg-brand')
  if (await vb.evaluate((el) => el.tagName === 'SELECT')) await vb.selectOption({ index: 1 }); else await vb.fill('Toyota')
  const vm = page.locator('#reg-model')
  if (await vm.evaluate((el) => el.tagName === 'SELECT')) await vm.selectOption({ index: 1 }); else await vm.fill('Camry')
  await page.locator('#reg-vin').fill(('J' + uniq().toUpperCase() + 'ABCDEFGHJKLMN').replace(/[IOQ]/g, 'A').slice(0, 17))
  await page.getByRole('button', { name: /^next/i }).click()
  await page.getByRole('button', { name: /skip for now/i }).click()
  await page.getByRole('button', { name: /register item/i }).click()
  await expect(page).toHaveURL(/\/device\//, { timeout: 20_000 })
})

test('an item already registered to someone else offers a claim instead', async ({ page }) => {
  const seller = await apiAs('user2')
  const list = await (await seller.get('/api/user-portal/devices')).json()
  const phone = list.data.devices.find((d: any) => d.imei)
  await seller.dispose()
  await page.goto('/register-device')
  await page.getByRole('radio', { name: /phone/i }).click()
  const brand = page.locator('#reg-brand')
  if (await brand.evaluate((el) => el.tagName === 'SELECT')) await brand.selectOption({ index: 1 }); else await brand.fill('Apple')
  const model = page.locator('#reg-model')
  if (await model.evaluate((el) => el.tagName === 'SELECT')) await model.selectOption({ index: 1 }); else await model.fill('iPhone')
  await page.locator('#reg-imei').fill(phone.imei)
  await page.getByRole('button', { name: /^next/i }).click()
  await page.getByRole('button', { name: /skip for now/i }).click()
  await page.getByRole('button', { name: /register item/i }).click()
  await expect(page.getByText(/already registered to another account/i)).toBeVisible()
  await expect(page.getByRole('link', { name: /claim this item/i })).toBeVisible()
})
